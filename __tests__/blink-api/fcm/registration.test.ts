import { Buffer } from 'node:buffer';
import { createECDH } from 'node:crypto';
import { checkin_proto } from '@eneris/push-receiver/dist/protos';
import createKeys from '@eneris/push-receiver/dist/keys';
import { registerGoogleIdentity } from '../../../src/blink-api/fcm/registration';
import { FCM_BUNDLE_ID, validCredentials, type Credentials } from '../../../src/blink-api/fcm/types';

const firebase = { projectId: 'test-project', appId: '1:123:android:fixture', apiKey: 'public-test-key', messagingSenderId: '123' };
const originalFetch = globalThis.fetch;
function credentials(): Credentials {
  const key = createECDH('prime256v1'); key.setPrivateKey(Buffer.alloc(32, 1));
  return {
    gcm: { androidId: '12345', securityToken: '67890', token: 'owned-gcm', appId: 'owned-instance' },
    fcm: { token: 'owned-fcm', installation: { token: 'owned-auth', refreshToken: 'owned-refresh', fid: 'owned-fid',
      createdAt: Date.now(), expiresIn: 604800000 } },
    keys: { privateKey: key.getPrivateKey('base64'), publicKey: key.getPublicKey('base64'), authSecret: Buffer.alloc(16, 1).toString('base64') },
    config: { projectId: firebase.projectId, vapidKey: '', bundleId: FCM_BUNDLE_ID },
  };
}
afterEach(() => { globalThis.fetch = originalFetch; });

it('restores the exact base64url key format generated by the pinned receiver', async () => {
  const cached = { ...credentials(), keys: await createKeys() };
  expect(validCredentials(cached, firebase)).toBe(true);
  const response = checkin_proto.AndroidCheckinResponse.fromObject({ androidId: 12345, securityToken: 67890 });
  const bytes = checkin_proto.AndroidCheckinResponse.encode(response).finish();
  const fetch = jest.fn(async () => new globalThis.Response(Buffer.from(bytes)));
  globalThis.fetch = fetch;
  const restored = await registerGoogleIdentity(firebase, cached, []);
  expect(restored.keys).toEqual(cached.keys);
  expect(restored.fcm.token).toBe(cached.fcm.token);
  expect(fetch).toHaveBeenCalledTimes(1);
  expect(validCredentials({ ...cached, keys: { ...cached.keys, publicKey: cached.keys.publicKey + '!' } }, firebase)).toBe(false);
});

it('reuses a valid cached identity despite metadata key order and performs only its checkin', async () => {
  const cached = credentials();
  const response = checkin_proto.AndroidCheckinResponse.fromObject({ androidId: 12345, securityToken: 67890 });
  const bytes = checkin_proto.AndroidCheckinResponse.encode(response).finish();
  const fetch = jest.fn(async () => new globalThis.Response(Buffer.from(bytes)));
  globalThis.fetch = fetch;
  const result = await registerGoogleIdentity(firebase, cached, []);
  expect(result.gcm).toEqual(cached.gcm); expect(result.fcm.token).toBe(cached.fcm.token); expect(result.keys).toEqual(cached.keys);
  expect(fetch).toHaveBeenCalledTimes(1);
  expect(fetch).toHaveBeenCalledWith('https://android.clients.google.com/checkin', expect.objectContaining({ method: 'POST' }));
});

it.each([1, 31])('restores a valid %i-byte private scalar without replacing its identity', async privateBytes => {
  const cached = credentials();
  const key = createECDH('prime256v1'); key.setPrivateKey(Buffer.alloc(privateBytes, 1));
  cached.keys = { privateKey: key.getPrivateKey('base64url'), publicKey: key.getPublicKey('base64url'),
    authSecret: Buffer.alloc(16, 1).toString('base64url') };
  expect(validCredentials(cached, firebase)).toBe(true);
  const response = checkin_proto.AndroidCheckinResponse.fromObject({ androidId: 12345, securityToken: 67890 });
  const bytes = checkin_proto.AndroidCheckinResponse.encode(response).finish();
  const fetch = jest.fn(async () => new globalThis.Response(Buffer.from(bytes)));
  globalThis.fetch = fetch;
  const restored = await registerGoogleIdentity(firebase, cached, []);
  expect(restored.keys).toEqual(cached.keys);
  expect(restored.fcm.token).toBe(cached.fcm.token);
  expect(fetch).toHaveBeenCalledTimes(1);
  expect(fetch).toHaveBeenCalledWith('https://android.clients.google.com/checkin', expect.objectContaining({ method: 'POST' }));
});

it.each([
  ['zero', Buffer.alloc(32)],
  ['out-of-range', Buffer.alloc(32, 255)],
  ['oversize', Buffer.alloc(33, 1)],
  ['truncated/mismatched', Buffer.alloc(31, 1)],
] as const)('rejects a %s private scalar before making a request', async (_reason, privateKey) => {
  const cached = credentials();
  cached.keys.privateKey = privateKey.toString('base64url');
  const fetch = jest.fn(); globalThis.fetch = fetch;
  expect(validCredentials(cached, firebase)).toBe(false);
  await expect(registerGoogleIdentity(firebase, cached, [])).rejects.toThrow('Invalid Google receiver identity');
  expect(fetch).not.toHaveBeenCalled();
});

it('rejects a cache for another project or bundle before calling Google', async () => {
  const fetch = jest.fn(); globalThis.fetch = fetch;
  const cached = credentials();
  await expect(registerGoogleIdentity(firebase, { ...cached, config: { ...cached.config, bundleId: 'another-client' } }, [])).rejects.toThrow();
  await expect(registerGoogleIdentity(firebase, { ...cached, config: { ...cached.config, projectId: 'another-project' } }, [])).rejects.toThrow();
  expect(fetch).not.toHaveBeenCalled();
});
